/**
 * Pine Script drawing objects — `line`, `label`, `box`, `table`.
 *
 * `line` and `label` arrived June 2019, `box` and `table` in May 2021, all
 * under v4 (see the v4 release notes). The registry split in ./index.ts keeps
 * the whole set out of the v1–v3 view, so a v3 script naming `label.new` is
 * refused there rather than by a check here.
 *
 * ── WHAT THIS DOES AND DOES NOT DO ──────────────────────────────────────────
 *
 * A drawing is recorded on the Context with an id and its properties, and the
 * setters mutate that record. It is NOT rendered, and it does not participate
 * in `plots` — a drawing is an object with a lifetime, not a per-bar value, and
 * TradingView's exported chart data does not contain drawings either. So
 * nothing here can affect the golden-parity numbers.
 *
 * The point is that a script which draws RUNS. A large fraction of published v4
 * indicators label their signals, and before this they died on the first
 * `label.new` — which said nothing about whether their arithmetic was right.
 *
 * Getters return what was set. `line.get_price(id, x)` is the one that computes
 * rather than recalls, because it is the only one a script reads back into its
 * own maths.
 */

import { Context } from "../context";
import { val } from "../../../utils/v2/common";

const v = (x: any): any => val(x);
const n = (x: any): number => Number(val(x));

/**
 * ⚠ EVERY MEMBER BELOW IS WRITTEN OUT LITERALLY, AND MUST STAY THAT WAY.
 *
 * The registry is generated by scripts/generate-metadata.ts, which walks these
 * object literals with ts-morph and records each PropertyAssignment it finds.
 * It does not evaluate the file — so a member added by a spread
 *
 *     ...setters("line", ["x1", "y1", …])
 *
 * exists at run time and is invisible to the generator. The first draft of this
 * file did exactly that: `line.get_price` worked, because it was a literal
 * property, while `line.get_y2` came back "The provided reference is not a
 * function" — the sandbox had no entry to call.
 *
 * So the repetition is load-bearing. These two helpers hold the shared BODY;
 * the property names have to be spelled out.
 */

/** Assigns a property on a drawing, coercing through `val`. */
function setProp(ctx: Context, id: any, fn: string, prop: string, value: any): void {
    ctx.getDrawing(id, fn).props[prop] = v(value);
}

/** Assigns a NUMERIC property — coordinates and widths. */
function setNum(ctx: Context, id: any, fn: string, prop: string, value: any): void {
    ctx.getDrawing(id, fn).props[prop] = n(value);
}

/** Recalls a property. */
function getProp(ctx: Context, id: any, fn: string, prop: string): any {
    return ctx.getDrawing(id, fn).props[prop];
}

// ── line ────────────────────────────────────────────────────────────────────

export const line = {
    new: (
        ctx: Context, x1: any, y1: any, x2: any, y2: any,
        xloc: any = "bar_index", extend: any = "none",
        color: any = "#2196F3", style: any = "solid", width: any = 1,
    ) => ctx.newDrawing("line", {
        x1: n(x1), y1: n(y1), x2: n(x2), y2: n(y2),
        xloc: v(xloc), extend: v(extend), color: v(color), style: v(style), width: n(width),
    }),

    set_x1: (ctx: Context, id: any, x: any) => setNum(ctx, id, "line.set_x1", "x1", x),
    set_y1: (ctx: Context, id: any, y: any) => setNum(ctx, id, "line.set_y1", "y1", y),
    set_x2: (ctx: Context, id: any, x: any) => setNum(ctx, id, "line.set_x2", "x2", x),
    set_y2: (ctx: Context, id: any, y: any) => setNum(ctx, id, "line.set_y2", "y2", y),
    set_width: (ctx: Context, id: any, width: any) => setNum(ctx, id, "line.set_width", "width", width),
    set_xloc: (ctx: Context, id: any, xloc: any) => setProp(ctx, id, "line.set_xloc", "xloc", xloc),
    set_extend: (ctx: Context, id: any, extend: any) => setProp(ctx, id, "line.set_extend", "extend", extend),
    set_color: (ctx: Context, id: any, color: any) => setProp(ctx, id, "line.set_color", "color", color),
    set_style: (ctx: Context, id: any, style: any) => setProp(ctx, id, "line.set_style", "style", style),

    get_x1: (ctx: Context, id: any) => getProp(ctx, id, "line.get_x1", "x1"),
    get_y1: (ctx: Context, id: any) => getProp(ctx, id, "line.get_y1", "y1"),
    get_x2: (ctx: Context, id: any) => getProp(ctx, id, "line.get_x2", "x2"),
    get_y2: (ctx: Context, id: any) => getProp(ctx, id, "line.get_y2", "y2"),

    /** Both endpoints at once — one call in Pine, so one call here. */
    set_xy1: (ctx: Context, id: any, x: any, y: any) => {
        const p = ctx.getDrawing(id, "line.set_xy1").props;
        p.x1 = n(x); p.y1 = n(y);
    },
    set_xy2: (ctx: Context, id: any, x: any, y: any) => {
        const p = ctx.getDrawing(id, "line.set_xy2").props;
        p.x2 = n(x); p.y2 = n(y);
    },

    /**
     * The price the line takes at bar `x`, by linear interpolation through its
     * two endpoints — extrapolated beyond them, which is what makes the
     * trendline-projection idiom work.
     *
     * Vertical lines have no single price, so they are `na` rather than ±∞.
     */
    get_price: (ctx: Context, id: any, x: any) => {
        const p = ctx.getDrawing(id, "line.get_price").props;
        if (p.x2 === p.x1) return NaN;
        return p.y1 + (p.y2 - p.y1) * ((n(x) - p.x1) / (p.x2 - p.x1));
    },

    delete: (ctx: Context, id: any) => {
        ctx.drawings.delete(String(v(id)));
    },
    copy: (ctx: Context, id: any) =>
        ctx.newDrawing("line", { ...ctx.getDrawing(id, "line.copy").props }),

    // Style constants.
    style_solid: "solid",
    style_dotted: "dotted",
    style_dashed: "dashed",
    style_arrow_left: "arrow_left",
    style_arrow_right: "arrow_right",
    style_arrow_both: "arrow_both",
};

