// ── table ───────────────────────────────────────────────────────────────────

export const table = {
    new: (
        ctx: Context, position: any, columns: any, rows: any,
        bgcolor: any = null, frame_color: any = null, frame_width: any = 0,
        border_color: any = null, border_width: any = 0,
    ) => ctx.newDrawing("table", {
        position: v(position), columns: n(columns), rows: n(rows),
        bgcolor: v(bgcolor), frame_color: v(frame_color), frame_width: n(frame_width),
        border_color: v(border_color), border_width: n(border_width),
        // Cells are sparse — a table is usually mostly empty, and a dense
        // rows×columns allocation would be built on every bar.
        cells: new Map<string, Record<string, any>>(),
    }),

    cell: (
        ctx: Context, table_id: any, column: any, row: any, text: any = "",
        width: any = 0, height: any = 0, text_color: any = "#000000",
        text_halign: any = "center", text_valign: any = "center",
        text_size: any = "normal", bgcolor: any = null,
    ) => {
        const p = ctx.getDrawing(table_id, "table.cell").props;
        p.cells.set(`${n(column)},${n(row)}`, {
            text: String(v(text) ?? ""), width: n(width), height: n(height),
            text_color: v(text_color), text_halign: v(text_halign),
            text_valign: v(text_valign), text_size: v(text_size), bgcolor: v(bgcolor),
        });
    },

    set_cell_text: (ctx: Context, table_id: any, column: any, row: any, text: any) => {
        const p = ctx.getDrawing(table_id, "table.set_cell_text").props;
        const key = `${n(column)},${n(row)}`;
        const cell = p.cells.get(key) ?? {};
        cell.text = String(v(text) ?? "");
        p.cells.set(key, cell);
    },

    set_position: (ctx: Context, id: any, position: any) => {
        ctx.getDrawing(id, "table.set_position").props.position = v(position);
    },
    set_bgcolor: (ctx: Context, id: any, bgcolor: any) => {
        ctx.getDrawing(id, "table.set_bgcolor").props.bgcolor = v(bgcolor);
    },

    clear: (ctx: Context, id: any) => {
        ctx.getDrawing(id, "table.clear").props.cells.clear();
    },
    delete: (ctx: Context, id: any) => {
        ctx.drawings.delete(String(v(id)));
    },
};

