/**
 * Pine Script drawing objects — `line`, `label`, `box`, `table`.
 *
 * `line` and `label` arrived June 2019, `box` and `table` in May 2021, all
 * under v4 (see the v4 release notes). The registry split in ./index.ts keeps
 * the whole set out of the v1–v3 view, so a v3 script naming `label.new` is
 * refused there rather than by a check here.
 *
 * ── WHAT THIS DOES AND DOES NOT DO ──────────────────────────────────────────
 *
 * A drawing is recorded on the Context with an id and its properties, and the
 * setters mutate that record. It is NOT rendered, and it does not participate
 * in `plots` — a drawing is an object with a lifetime, not a per-bar value, and
 * TradingView's exported chart data does not contain drawings either. So
 * nothing here can affect the golden-parity numbers.
 *
 * The point is that a script which draws RUNS. A large fraction of published v4
 * indicators label their signals, and before this they died on the first
 * `label.new` — which said nothing about whether their arithmetic was right.
 *
 * Getters return what was set. `line.get_price(id, x)` is the one that computes
 * rather than recalls, because it is the only one a script reads back into its
 * own maths.
 */

import { Context } from "../context";
import { val } from "../../../utils/v2/common";

const v = (x: any): any => val(x);
const n = (x: any): number => Number(val(x));

/**
 * ⚠ EVERY MEMBER BELOW IS WRITTEN OUT LITERALLY, AND MUST STAY THAT WAY.
 *
 * The registry is generated by scripts/common/generate-metadata.ts, which walks these
 * object literals with ts-morph and records each PropertyAssignment it finds.
 * It does not evaluate the file — so a member added by a spread
 *
 *     ...setters("line", ["x1", "y1", …])
 *
 * exists at run time and is invisible to the generator. The first draft of this
 * file did exactly that: `line.get_price` worked, because it was a literal
 * property, while `line.get_y2` came back "The provided reference is not a
 * function" — the sandbox had no entry to call.
 *
 * So the repetition is load-bearing. These two helpers hold the shared BODY;
 * the property names have to be spelled out.
 */

/** Assigns a property on a drawing, coercing through `val`. */
function setProp(ctx: Context, id: any, fn: string, prop: string, value: any): void {
    ctx.getDrawing(id, fn).props[prop] = v(value);
}

/** Assigns a NUMERIC property — coordinates and widths. */
function setNum(ctx: Context, id: any, fn: string, prop: string, value: any): void {
    ctx.getDrawing(id, fn).props[prop] = n(value);
}

/** Recalls a property. */
function getProp(ctx: Context, id: any, fn: string, prop: string): any {
    return ctx.getDrawing(id, fn).props[prop];
}


/**
 * The `chart.point` overloads of `line.new`, `box.new` and `label.new`.
 *
 * SOURCING. October 2023, alongside polylines. From the manual's Lines and
 * boxes page, the first overload of each:
 *
 *   line.new(first_point, second_point, xloc, extend, color, style, width)
 *   box.new(top_left, bottom_right, border_color, border_width, border_style,
 *           extend, xloc, bgcolor, text, text_size, …)
 *   label.new(point, text, xloc, yloc, color, style, textcolor, size, …)
 *
 * and the rule for the x it takes: "Whether it uses the `index` or `time`
 * fields … as x-coordinates depends on the function's `xloc` value."
 *
 * ── The failure this closes ─────────────────────────────────────────────────
 *
 * Only the coordinate form existed, so `line.new(firstPoint, secondPoint)` read
 * a chart point where a number belongs: `Number({index, time, price})` is NaN,
 * and the line was created at (NaN, NaN)-(NaN, NaN). Nothing raised — a
 * drawing with na coordinates is legal Pine, and TradingView's `line.get_price`
 * on one legitimately returns na. Eighteen corpus files use these overloads,
 * and `v5-language-loops-17` is what surfaced it: its `avgActivePivot` divides
 * by a count of lines it can never read a price from, so the plot was na on
 * every bar of a page whose whole subject is that line.
 *
 * ── How a call is resolved ──────────────────────────────────────────────────
 *
 * Both overloads are one JavaScript function, because the registry holds one
 * signature per name and `Context.call` binds keyword arguments against it.
 * That signature is the COORDINATE form, so a keyword lands in the slot its
 * name has there; a POSITIONAL argument lands where the caller put it, which
 * in the point form is `drop` slots earlier.
 *
 * Beyond the coordinates the two lists carry the same names in the same order
 * — `line.new`'s 5th coordinate-form parameter and its 3rd point-form one are
 * both `xloc` — so a parameter can be read from its keyword slot, falling back
 * to its positional one. Every call in the corpus resolves; a call that passed
 * one parameter positionally AND another by keyword from an earlier slot could
 * not, and Pine has no way to write one.
 */
function isChartPoint(x: any): boolean {
    const p = val(x);
    return !!p && typeof p === "object" && !Array.isArray(p)
        && ("index" in p || "time" in p) && "price" in p;
}

/**
 * The tail of a point-form call, re-read against the coordinate signature.
 *
 * `drop` is how many coordinate parameters the point form replaces: two for
 * `line` and `box` (x1,y1,x2,y2 → two points), one for `label` (x,y → one).
 * `names` are the point form's remaining parameters in order, starting at
 * point-index `from`.
 *
 * A KEYWORD argument was bound by `Context.call` against the coordinate
 * signature, so it sits `drop` slots to the right of where the point form puts
 * it. A POSITIONAL argument sits exactly where the caller wrote it. The two
 * lists carry the same names in the same order past the coordinates —
 * `line.new`'s 5th coordinate-form parameter and its 3rd point-form one are
 * both `xloc` — so the call's own shape decides which slot to read, and
 * `Context` records that shape for exactly this.
 *
 * Guessing instead of asking does not work, in either direction. Preferring the
 * keyword slot reads `label.new(p, "hi", xloc.bar_time, …)`'s third argument as
 * the label's TEXT; preferring the positional slot reads
 * `label.new(p, "hi", style = label.style_circle)`'s style as its TEXTCOLOR,
 * because that keyword landed in the slot the point form gives to textcolor.
 *
 * The three `new` functions declare no parameter defaults, and apply them
 * through `or` below: a JavaScript default fires before the body runs, so a
 * parameter the caller never wrote would arrive here indistinguishable from
 * one it did.
 */
function pointTail(
    ctx: Context, args: any[], drop: number, from: number, names: readonly string[],
): any[] {
    return names.map((name, k) => {
        const j = from + k;
        if (ctx.keywordArguments.has(name)) return args[j + drop];
        return j < ctx.positionalArguments ? args[j] : undefined;
    });
}

/** Each overload's parameters past the points, in the order the manual lists them. */
const LINE_TAIL = ["xloc", "extend", "color", "style", "width"] as const;
const BOX_TAIL = ["border_color", "border_width", "border_style", "extend", "xloc",
                  "bgcolor", "text", "text_size", "text_color", "text_halign",
                  "text_valign", "text_wrap", "text_font_family"] as const;
const LABEL_TAIL = ["text", "xloc", "yloc", "color", "style", "textcolor", "size",
                    "textalign", "tooltip", "text_font_family"] as const;

/** A supplied argument, or the manual's default when there is none. */
function or(supplied: any, fallback: any): any {
    return supplied !== undefined ? supplied : fallback;
}

/** The x a point contributes, given the drawing's own `xloc`. */
function pointX(point: any, xloc: any): number {
    const at = val(point) ?? {};
    return n(val(xloc) === "bar_time" ? at.time : at.index);
}

/** The price a point carries. */
function pointY(point: any): number {
    return n((val(point) ?? {}).price);
}

// ── line ────────────────────────────────────────────────────────────────────

/**
 * Moves one endpoint of a drawing to a `chart.point`.
 *
 * The point carries `index`, `time` and `price`; which x it contributes is the
 * DRAWING's `xloc`, because that is what the drawing will be placed by. A point
 * built with `from_index` has no time and one built with `from_time` has no
 * index, so reading the wrong one silently moves the drawing to `na`.
 */
function setEndpoint(ctx: Context, id: any, fn: string, point: any,
                     xKey: string, yKey: string): void {
    const p = ctx.getDrawing(id, fn).props;
    const at = v(point) ?? {};
    p[xKey] = n(p.xloc === "bar_time" ? at.time : at.index);
    p[yKey] = n(at.price);
}

export const line = {
    /**
     * `line.new(x1, y1, x2, y2, …)` and `line.new(first_point, second_point, …)`
     * — see the note above `isChartPoint` for how the two are told apart, and
     * why nothing here carries a parameter default.
     */
    new: (
        ctx: Context, x1: any, y1: any, x2: any, y2: any,
        xloc?: any, extend?: any, color?: any, style?: any, width?: any,
    ) => {
        const points = isChartPoint(x1);
        const [xl, ex, co, st, wd] = points
            ? pointTail(ctx, [x1, y1, x2, y2, xloc, extend, color, style, width],
                        2, 2, LINE_TAIL)
            : [xloc, extend, color, style, width];
        const where = or(xl, "bar_index");
        return ctx.newDrawing("line", {
            x1: points ? pointX(x1, where) : n(x1),
            y1: points ? pointY(x1)        : n(y1),
            x2: points ? pointX(y1, where) : n(x2),
            y2: points ? pointY(y1)        : n(y2),
            xloc: v(where), extend: v(or(ex, "none")), color: v(or(co, "#2196F3")),
            style: v(or(st, "solid")), width: n(or(wd, 1)),
        });
    },

    set_x1: (ctx: Context, id: any, x: any) => setNum(ctx, id, "line.set_x1", "x1", x),
    set_y1: (ctx: Context, id: any, y: any) => setNum(ctx, id, "line.set_y1", "y1", y),
    set_x2: (ctx: Context, id: any, x: any) => setNum(ctx, id, "line.set_x2", "x2", x),
    set_y2: (ctx: Context, id: any, y: any) => setNum(ctx, id, "line.set_y2", "y2", y),
    set_width: (ctx: Context, id: any, width: any) => setNum(ctx, id, "line.set_width", "width", width),
    set_xloc: (ctx: Context, id: any, xloc: any) => setProp(ctx, id, "line.set_xloc", "xloc", xloc),
    set_extend: (ctx: Context, id: any, extend: any) => setProp(ctx, id, "line.set_extend", "extend", extend),
    set_color: (ctx: Context, id: any, color: any) => setProp(ctx, id, "line.set_color", "color", color),
    set_style: (ctx: Context, id: any, style: any) => setProp(ctx, id, "line.set_style", "style", style),

    get_x1: (ctx: Context, id: any) => getProp(ctx, id, "line.get_x1", "x1"),
    get_y1: (ctx: Context, id: any) => getProp(ctx, id, "line.get_y1", "y1"),
    get_x2: (ctx: Context, id: any) => getProp(ctx, id, "line.get_x2", "x2"),
    get_y2: (ctx: Context, id: any) => getProp(ctx, id, "line.get_y2", "y2"),

    /** Both endpoints at once — one call in Pine, so one call here. */
    set_xy1: (ctx: Context, id: any, x: any, y: any) => {
        const p = ctx.getDrawing(id, "line.set_xy1").props;
        p.x1 = n(x); p.y1 = n(y);
    },
    set_xy2: (ctx: Context, id: any, x: any, y: any) => {
        const p = ctx.getDrawing(id, "line.set_xy2").props;
        p.x2 = n(x); p.y2 = n(y);
    },

    /**
     * `line.set_first_point(id, point)` / `set_second_point` — the `chart.point`
     * spellings of `set_xy1` / `set_xy2`, October 2023.
     *
     * A point carries BOTH x coordinates, and which one applies is the line's
     * own `xloc` — so the drawing decides, not the point. That is the whole
     * reason these exist beside the xy pair: a script that works in
     * `chart.point`s should not have to unpack one to move a line.
     */
    set_first_point: (ctx: Context, id: any, point: any) =>
        setEndpoint(ctx, id, "line.set_first_point", point, "x1", "y1"),
    set_second_point: (ctx: Context, id: any, point: any) =>
        setEndpoint(ctx, id, "line.set_second_point", point, "x2", "y2"),

    /**
     * The price the line takes at bar `x`, by linear interpolation through its
     * two endpoints — extrapolated beyond them, which is what makes the
     * trendline-projection idiom work.
     *
     * Vertical lines have no single price, so they are `na` rather than ±∞.
     */
    get_price: (ctx: Context, id: any, x: any) => {
        const p = ctx.getDrawing(id, "line.get_price").props;
        if (p.x2 === p.x1) return NaN;
        return p.y1 + (p.y2 - p.y1) * ((n(x) - p.x1) / (p.x2 - p.x1));
    },

    delete: (ctx: Context, id: any) => {
        ctx.deleteDrawing(v(id));
    },

    /**
     * `line.all` — every live line, oldest first.
     *
     * A Pine ARRAY, so `array.size(line.all)` and `line.all.size()` both work, and
     * so does iterating it to delete the oldest. `polyline.all` and
     * `linefill.all` are the same thing; these three were simply missing, and a
     * missing member of a real namespace read as `undefined` — which made
     * `array.size(label.all)` a call on nothing.
     *
     * @getter
     */
    all: (ctx: Context): string[] => ctx.drawingIds("line"),

    copy: (ctx: Context, id: any) =>
        ctx.newDrawing("line", { ...ctx.getDrawing(id, "line.copy").props }),

    // Style constants.
    style_solid: "solid",
    style_dotted: "dotted",
    style_dashed: "dashed",
    style_arrow_left: "arrow_left",
    style_arrow_right: "arrow_right",
    style_arrow_both: "arrow_both",
};

