import { Context } from "../context";

export const __IS_NAMESPACE__ = true;

/**
 * Returns true if the current bar is a historical bar.
 * @getter
 */
export function ishistory(ctx: Context): boolean {
    return ctx.is_history;
}

/**
 * Returns true if the current bar is a real-time bar.
 * @getter
 */
export function isrealtime(ctx: Context): boolean {
    return ctx.is_realtime;
}

/**
 * Returns true if this is the first execution on the current bar.
 * @getter
 */
export function isnew(ctx: Context): boolean {
    return ctx.is_new;
}

/**
 * Returns true if this is the last historically available bar.
 * @getter
 */
export function islast(ctx: Context): boolean {
    return ctx.onLastBar;
}

/**
 * Returns true on the script's FIRST bar.
 *
 * Derived from the bar counter rather than stored as a flag, so it cannot fall
 * out of step with `bar_index` — they are the same fact.
 *
 * Present in Pine since v1 and absent here until v5 needed it: every harness
 * generated by scripts/common/make-log-harness.ts writes its CSV header under
 * `if barstate.isfirst`, and a missing member of an EXISTING namespace reads as
 * `undefined` rather than erroring (the namespace-root check in the emitter
 * deliberately does not assert registry completeness), so the header was
 * silently never emitted.
 *
 * @getter
 */
export function isfirst(ctx: Context): boolean {
    return ctx.currentBarIndex === 0;
}

/**
 * True on every historical bar, and on a realtime bar's CLOSING update.
 *
 * "barstate.isconfirmed is true on all historical bars and on the last
 *  (closing) update of a realtime bar."
 *
 * The bar's values will not change again once this is true, which is why it is
 * the standard guard around anything a script must do once per bar — an alert,
 * a log line, a queue push. Eighteen of TradingView's own examples use it, and
 * every one of them was reading `undefined`: a missing member of an EXISTING
 * namespace does not error, so `if barstate.isconfirmed` was silently never
 * taken and the scripts drew nothing.
 *
 * "The last (closing) update of a realtime bar" is not a script execution in
 * this engine: `Context.commitBar` settles the forming bar AFTER the script has
 * run, so a bar is either history — settled — or forming. That makes the test
 * exactly `not realtime`, which is the first half of the definition and the
 * whole of it here.
 *
 * @getter
 */
export function isconfirmed(ctx: Context): boolean {
    return !ctx.is_realtime;
}

/**
 * True on the last bar the script can treat as settled history.
 *
 * "barstate.islastconfirmedhistory is true if the script is executing on the
 *  dataset's last bar when the market is closed, or on the bar immediately
 *  preceding the realtime bar if the market is open."
 *
 * Two readings of one idea, and which applies depends on whether a realtime bar
 * exists at all. With no realtime bar the last bar IS the last confirmed one;
 * with one, the bar before it is.
 *
 * The commonest guard in TradingView's documentation — twenty-nine examples
 * draw their tables and labels under it, because it fires exactly once and on
 * the rightmost settled bar.
 *
 * @getter
 */
export function islastconfirmedhistory(ctx: Context): boolean {
    if (ctx.is_realtime) return false;

    // No realtime tail — the market is closed, and the dataset's last bar IS
    // the last confirmed one. `is_last` says so on its own.
    if (ctx.realtimeBars === 0) return ctx.onLastBar;

    // With a realtime tail the answer is due one bar BEFORE `is_last` is ever
    // true, so it cannot come from that flag; it comes from the declared
    // extent. A host that runs a realtime bar without declaring how far the
    // dataset goes has not said enough to answer, and gets `false` rather than
    // a guess — the same stance `last_bar_index` takes.
    //
    // This is what was wrong: the old reading was `is_realtime ? false :
    // is_last`, and under the convention every harness here uses — the final
    // bar run as realtime — no bar is both the last one and historical. The
    // guard fired on NOTHING, and the twenty-nine documentation examples that
    // draw their labels and tables under it drew nothing at all.
    return ctx.datasetSize != null
        && ctx.currentBarIndex === ctx.lastConfirmedHistoryIndex;
}
